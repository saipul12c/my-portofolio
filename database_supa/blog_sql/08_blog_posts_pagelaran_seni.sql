Dalam Pagelaran Seni 2024 Angkatan 22 UIN Antasari Banjarmasin, divisi tata rias dan busana memikul tugas etnografis yang sangat menantang: bagaimana menginterpretasikan kembali warisan busana adat Banjar ke dalam konteks panggung teater modern tanpa kehilangan marwah kesakralan dan akurasi sejarahnya. Kalimantan Selatan memiliki kekayaan tekstil dan ragam hias tradisional yang sangat kaya, mulai dari kain tenun ikat Sasirangan dengan motif-motif magis kuno hingga hiasan kepala keemasan bertatahkan permata sintetis yang anggun.

