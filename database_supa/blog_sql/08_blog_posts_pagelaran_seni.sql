## Seni Rias Karakter: Memahat Wajah, Menghidupkan Ekspresi

Merias wajah untuk panggung teater auditorium sangat berbeda dengan merias wajah untuk wisuda atau pesta pernikahan (*beauty makeup*). Di panggung pementasan dengan jarak pandang penonton hingga puluhan meter di bawah terpaan lampu sorot berkekuatan ribuan watt, riasan wajah yang tipis akan tampak pucat dan datar seperti topeng lilin. Tim perias harus menerapkan teknik *stage character makeup* yang kontras dan terstruktur tebal.

Teknik konturing (*shading and highlighting*) digunakan secara ekstrem untuk memahat struktur tulang wajah para aktor. Garis-garis rahang ditegaskan, rongga mata diperdalam dengan gradasi bayangan gelap, dan garis senyum atau kerutan dahi digambar manual menggunakan kuas runcing agar watak penuaan dan beban derita karakter antagonis maupun protagonis dapat terbaca dengan jelas oleh penonton yang duduk di baris paling belakang gedung.

Ketelitian tingkat tinggi juga diterapkan pada riasan para penari. Alis dibentuk melengkung anggun (*alis bulan sabit*) khas putri keraton Banjar, kelopak mata dihiasi sapuan warna emas berkilau (*gold shimmer*) yang memantulkan cahaya panggung secara menawan, dan rona merah di bibir diaplikasikan dengan teknik khusus agar tahan terhadap keringat selama bermenit-menit menari di bawah panas lampu panggung tanpa luntur sedikit pun.

