## Filosofi Kain Sasirangan: Rajutan Doa di Setiap Jelujur Motif

Elemen visual paling menonjol pada busana para penari dan pemeran wanita adalah aplikasi kain Sasirangan. Sasirangan, yang secara etimologis berasal dari kata bahasa Banjar *sa-sirang* yang berarti dijahit-jelujur lalu ditarik kencang sebelum dicelup warna, pada mulanya diciptakan sebagai kain *pamintaan* (kain penyembuh) yang sarat dengan muatan doa dan tolak bala bagi masyarakat Banjar tempo dulu.

Dalam busana penari Lokal C yang dibawakan oleh Helda, Nida, Adaw, Danti, dan Yulia, motif Sasirangan yang dipilih dirancang khusus mencerminkan karakter pertunjukan. Motif *Gigi Haruan* (gigi ikan gabus) disematkan pada tepi rompi sebagai simbol ketajaman pikiran dan keteguhan prinsip; motif *Kambang Kacang* melambangkan kerendahan hati dan keakraban sosial; serta motif *Bintang Bahambur* yang menghiasi selendang sutra panjang sebagai perlambang cita-cita luhur generasi muda yang menyebar menerangi kegelapan malam.

